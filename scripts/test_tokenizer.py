from transformers import WhisperTokenizer

def analyze_sinhala_tokens():
    print("Downloading Whisper V3 Tokenizer...")
    # Load the standard Whisper tokenizer
    tokenizer = WhisperTokenizer.from_pretrained("openai/whisper-large-v3")

    # A complex Sinhala word with ZWJ (Zero Width Joiner), Rakaransaya, and Yansaya
    # "ක්‍රියා" (Kriya - Action/Verb)
    sinhala_text = "ක්‍රියා"

    print("-" * 40)
    print(f"Original Text: {sinhala_text}")
    print(f"Actual Character Count (Expected): 6")
    
    # Encode the text into token IDs
    tokens = tokenizer.encode(sinhala_text, add_special_tokens=False)
    
    print(f"Total Tokens Generated by Whisper: {len(tokens)}")
    print("-" * 40)
    print("Token Breakdown (Notice how the word is fragmented):")
    
    for token in tokens:
        decoded_chunk = tokenizer.decode([token])
        print(f"Token ID: {token:<6} -> Visual Chunk: '{decoded_chunk}'")

if __name__ == "__main__":
    analyze_sinhala_tokens()